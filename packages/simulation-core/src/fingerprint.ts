import type { SimulationState } from '@vlab/contracts';

/** JSON with object keys sorted recursively, so equal states serialize identically. */
export const canonicalJson = (value: unknown): string =>
  JSON.stringify(value, (_key, v: unknown) =>
    v && typeof v === 'object' && !Array.isArray(v)
      ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
      : v,
  );

/** cyrb53: fast, deterministic, non-cryptographic 53-bit hash. */
const cyrb53 = (str: string): string => {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16).padStart(14, '0');
};

/** Fingerprint of laboratory state plus the inputs that affect future transitions. */
export const fingerprint = (state: Pick<SimulationState, 'lab' | 'meta'>): string =>
  cyrb53(
    canonicalJson({ lab: state.lab, rngState: state.meta.rngState, attempt: state.meta.attempt }),
  );
